import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const publicRoot=resolve(root,'public');
const sources=JSON.parse(await readFile(resolve(root,'scripts/storefront-styles.json'),'utf8'));
const chunks=[];
for(const href of sources){
 const name=href.split('?')[0].replace(/^\//,'');
 if(!/^[a-z0-9-]+\.css$/.test(name))throw Error(`Unexpected stylesheet path: ${href}`);
 let css=await readFile(resolve(publicRoot,name),'utf8');
 // style.css originally imports dialogs.css first. Inline it in the same position.
 css=css.replace(/@import\s+url\(['"]?dialogs\.css['"]?\);/g,()=> '__CAMICAT_DIALOGS__');
 if(css.includes('__CAMICAT_DIALOGS__'))css=css.replace('__CAMICAT_DIALOGS__',await readFile(resolve(publicRoot,'dialogs.css'),'utf8'));
 if(/@import\b/.test(css))throw Error(`Unresolved CSS import: ${name}`);
 chunks.push(`/* Source: ${name} */\n${css}\n`);
}
const output='/* Generated by scripts/build-storefront-styles.mjs. Edit source styles, then rebuild. */\n'+chunks.join('\n');
await writeFile(resolve(publicRoot,'storefront-bundle.css'),output);
process.stdout.write(`Built ${sources.length} ordered stylesheets into storefront-bundle.css (${Buffer.byteLength(output)} bytes).\n`);
